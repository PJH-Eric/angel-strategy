  const FALL = { 'zh-CN': ['zh-TW'], ja: ['en', 'zh-TW'], ko: ['en', 'zh-TW'], en: ['zh-TW'], 'zh-TW': [] };
  function p(lang, key, vars) {
    if (!D[lang]) lang = 'zh-TW';
    let s = D[lang][key];
    if (s == null) { const f = FALL[lang] || []; for (let i = 0; i < f.length && s == null; i++) s = D[f[i]][key]; }
    if (s == null) return key;
    if (vars) Object.keys(vars).forEach(function (k) { s = s.split('{' + k + '}').join(String(vars[k])); });
    return s;
  }
  return { p: p, LANGS: Object.keys(D), D: D };
